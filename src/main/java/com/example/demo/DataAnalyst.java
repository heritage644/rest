package com.example.demo;
import java.util.Scanner;
public class DataAnalyst {
    private Integer id;
    private String name;
    private String  tools;


    public DataAnalyst (Integer id,String name, String tools){
        this.id = id;
        this.name = name;
        this.tools = tools;
    }
    public Integer getId (){
        return this.id;
    }
    public Integer getName (){
        return this.id;
    }
    public Integer getTools (){
        return this.id;
    }
    public Integer setId (){
        return this.id = id;
    }
    public String setName (){
        return this.name = name;
    }
    public String setTools (){
        return this.tools = tools;
    }
}
